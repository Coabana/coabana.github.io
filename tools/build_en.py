"""Generate en/index.html, the static English page, from index.html and js/i18n.js.

index.html carries the Spanish text; js/i18n.js holds both dictionaries.
This script writes the same page with every data-i18n text and attribute
taken from the `en` dictionary, the head's URLs and locale switched to
/en/, and relative paths made absolute, so crawlers that do not run
JavaScript (search engines, LinkedIn, WhatsApp) read an English page.

    python3 tools/build_en.py           # write en/index.html
    python3 tools/build_en.py --check   # exit 1 if en/index.html is stale

Standard library only; run from the repository root.
"""

import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "index.html"
DICTIONARIES = ROOT / "js" / "i18n.js"
OUTPUT = ROOT / "en" / "index.html"
SITE = "https://coabana.github.io/"

NOTICE = (
    "<!-- Generated by tools/build_en.py from index.html and js/i18n.js;"
    " do not edit by hand. -->\n"
)


def load_dictionary(lang):
    src = DICTIONARIES.read_text(encoding="utf-8")
    block = re.search(r"^  %s: \{\n(.*?)^  \}" % lang, src, re.S | re.M)
    if not block:
        sys.exit(f"js/i18n.js: no {lang} dictionary")
    entries = re.findall(r'^    "([^"]+)": (".*?"),?$', block.group(1), re.M)
    return {key: json.loads(value) for key, value in entries}


def replace_once(text, old, new):
    count = text.count(old)
    if count != 1:
        sys.exit(f"index.html: expected one {old!r}, found {count}")
    return text.replace(old, new)


def set_attribute(tag, name, value):
    pattern = re.compile(r'(\s%s=")[^"]*(")' % re.escape(name))
    if not pattern.search(tag):
        sys.exit(f"index.html: {tag[:60]!r} has no {name} attribute")
    return pattern.sub(lambda m: m.group(1) + html.escape(value) + m.group(2), tag, count=1)


def translate(page, en):
    def text(key):
        if key not in en:
            sys.exit(f"js/i18n.js: en has no {key!r}")
        return en[key]

    out, pos = [], 0
    for tag in re.finditer(r"<([a-zA-Z][a-zA-Z0-9]*)\b[^>]*>", page):
        out.append(page[pos:tag.start()])
        markup, name = tag.group(0), tag.group(1)
        for attr in ("placeholder", "aria-label", "content"):
            key = re.search(r'\sdata-i18n-%s="([^"]+)"' % attr, markup)
            if key:
                markup = set_attribute(markup, attr, text(key.group(1)))
        out.append(markup)
        pos = tag.end()
        key = re.search(r'\sdata-i18n="([^"]+)"', markup)
        if key:
            close = page.index("</%s>" % name, pos)
            if "<" in page[pos:close]:
                sys.exit(f"index.html: data-i18n={key.group(1)!r} holds markup")
            out.append(html.escape(text(key.group(1)), quote=False))
            pos = close
    out.append(page[pos:])
    return "".join(out)


def localize_head(page, en):
    page = replace_once(page, '<html lang="es"', '<html lang="en"')
    page = re.sub(r"<title>[^<]*</title>", "<title>%s</title>" % html.escape(en["meta.title"]), page, count=1)
    page = replace_once(page, '<link rel="canonical" href="%s">' % SITE, '<link rel="canonical" href="%sen/">' % SITE)
    page = replace_once(page, '<meta property="og:url" content="%s">' % SITE, '<meta property="og:url" content="%sen/">' % SITE)
    page = replace_once(page, '<meta property="og:locale" content="es_ES">', '<meta property="og:locale" content="en_US">')
    page = replace_once(page, '<meta property="og:locale:alternate" content="en_US">', '<meta property="og:locale:alternate" content="es_ES">')
    page = replace_once(page, '<meta property="og:image" content="%sog-image.jpg">' % SITE, '<meta property="og:image" content="%sog-image-en.jpg">' % SITE)
    page = replace_once(page, '<meta name="twitter:image" content="%sog-image.jpg">' % SITE, '<meta name="twitter:image" content="%sog-image-en.jpg">' % SITE)
    toggle = re.search(r'<button class="lang-toggle" id="langToggle"[^>]*>EN</button>', page)
    if not toggle:
        sys.exit("index.html: no language toggle")
    page = page.replace(
        toggle.group(0),
        set_attribute(toggle.group(0), "aria-label", "Cambiar a español").replace(">EN</button>", ">ES</button>"),
    )
    # The page lives one level down: its relative paths become absolute.
    page = re.sub(r'(\s(?:href|src)=")(?=(?:assets|css|js)/)', r"\1/", page)
    return page.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + NOTICE, 1)


def build():
    en = load_dictionary("en")
    es = load_dictionary("es")
    if set(en) != set(es):
        sys.exit("js/i18n.js: es and en keys differ")
    page = SOURCE.read_text(encoding="utf-8")
    return localize_head(translate(page, en), en)


def main():
    page = build()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != page:
            print("en/index.html is stale: run python3 tools/build_en.py")
            return 1
        print("en/index.html is in sync")
        return 0
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(page, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
